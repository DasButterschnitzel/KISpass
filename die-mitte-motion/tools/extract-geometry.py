#!/usr/bin/env python3
"""Generate src/brand/geometry.js from the original Die-Mitte production set.

Usage:
    python3 -I tools/extract-geometry.py <path-to/Die-Mitte-Produktionsset> > src/brand/geometry.js

Everything the motion system draws as "logo" is taken 1:1 from the production
SVGs (M-Signet, wordmark outlines, lockup transforms). The arc motif
(Bogenmotiv) is rebuilt as stacks of circles; the circle parameters were fitted
against the original PNG exports (<1 % pixel deviation, see README) and are
written out here as constants so they can be animated.
"""
import json
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
logo_dir = root / "01-Logo-und-Gestaltung"


def m_parts(svg_text):
    parts = re.findall(r'<path fill="(#[0-9A-Fa-f]{6})"[^>]*?\sd="([^"]+)"', svg_text)
    names = {"#1C1D20": "black", "#A21B25": "fold", "#D92C32": "red", "#F4C526": "gold"}
    return [{"id": names[f.upper()], "fill": f.upper(), "d": d} for f, d in parts]


def lockup(svg_text):
    vb = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg_text)
    m_tr = re.search(r'<g transform="translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\)">', svg_text)
    w_tr = re.search(r'<g fill="#[0-9A-Fa-f]{6}" transform="translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+) ([-\d.]+)\)">', svg_text)
    glyphs = re.findall(r'<path transform="translate\(([-\d.]+) 0\)" d="([^"]+)"/>', svg_text)
    return {
        "viewBox": [float(vb.group(1)), float(vb.group(2))],
        "m": {"x": float(m_tr.group(1)), "y": float(m_tr.group(2)), "s": float(m_tr.group(3))},
        "word": {"x": float(w_tr.group(1)), "y": float(w_tr.group(2)), "s": float(w_tr.group(3))},
    }, [{"x": float(x), "d": d} for x, d in glyphs]


signet = m_parts((logo_dir / "M-Signet.svg").read_text())
lock_h, glyphs = lockup((logo_dir / "Logo-horizontal.svg").read_text())
lock_s, glyphs_s = lockup((logo_dir / "Logo-gestapelt.svg").read_text())
assert [g["d"] for g in glyphs] == [g["d"] for g in glyphs_s], "wordmark differs between lockups"
chars = list("DieMitte")
for g, ch in zip(glyphs, chars):
    g["ch"] = ch

# Arc motif as circle stacks (back -> front), reference box 1774 x 887 (= Bogenmotiv*.svg viewBox).
# Fitted against Bogenmotiv.png / Bogenmotiv-Ecke.png. "clip" = index of a disc this disc is
# intersected with; "inner" = second tone painted inside the disc.
ARC_BOTTOM = [
    {"id": "hillL", "c": "mgray", "x": 2.5, "y": 1142, "r": 882},
    {"id": "hillR", "c": "mgray", "x": 1921.5, "y": 1295, "r": 989},
    {"id": "hillR2", "c": "lgray", "x": 2049, "y": 1104, "r": 620},
    {"id": "gold", "c": "gold", "x": 862, "y": 1404, "r": 957},
    {"id": "red", "c": "red", "x": 552.5, "y": 1098, "r": 636},
    {"id": "black", "c": "black", "x": 243, "y": 1044, "r": 544, "clip": "red"},
    {"id": "front", "c": "lgray", "x": -291, "y": 926.5, "r": 676,
     "inner": {"c": "mgray", "x": 565, "y": 1142, "r": 677}},
]
ARC_CORNER = [
    {"id": "lgray", "c": "lgray", "x": 1867.5, "y": 1176, "r": 948},
    {"id": "mgray", "c": "mgray", "x": 1610, "y": 1519, "r": 1132},
    {"id": "mgray2", "c": "mgray", "x": 1562.5, "y": 1170, "r": 781},
    {"id": "black", "c": "black", "x": 1633, "y": 1280, "r": 774},
    {"id": "red", "c": "red", "x": 1798.5, "y": 1066.5, "r": 652},
    {"id": "gold", "c": "gold", "x": 1988, "y": 962, "r": 608},
]

out = {
    "M_VIEWBOX": [1048, 613],
    "M_PARTS": signet,
    "WORDMARK": glyphs,
    "LOCKUP_H": lock_h,
    "LOCKUP_S": lock_s,
    "ARC_REF": [1774, 887],
    "ARC_BOTTOM": ARC_BOTTOM,
    "ARC_CORNER": ARC_CORNER,
}

print("// Generated by tools/extract-geometry.py from the Die-Mitte production set. Do not edit by hand.")
print("// Logo paths and lockup transforms are taken 1:1 from M-Signet.svg, Logo-horizontal.svg and")
print("// Logo-gestapelt.svg. Arc motifs are circle stacks fitted to Bogenmotiv(-Ecke).png.")
for k, v in out.items():
    print(f"export const {k} = {json.dumps(v, ensure_ascii=False)};")
